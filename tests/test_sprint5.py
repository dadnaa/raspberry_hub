def _make_ok_result():
    r = MagicMock()
    r.succeeded   = True
    r.elapsed_ms  = 10.0
    r.status.name = "OK"
    return r

def _make_fail_result():
    r = MagicMock()
    r.succeeded   = False
    r.elapsed_ms  = 5.0
    r.status.name = "TIMEOUT"
    return r


class TestJobExecutor(unittest.TestCase):

    def _make_executor(self, lines, engine_result=None, tmpdir=None):
        job = Job.create("p1", "http://x.com/f.gcode", lines)
        engine = MagicMock()
        engine.send.return_value = engine_result or _make_ok_result()
        store   = JobStore(storage_dir=Path(tmpdir or tempfile.mkdtemp()))
        pub     = MagicMock()
        finished = []
        exec_ = JobExecutor(
            job=job,
            command_engine=engine,
            store=store,
            publish_state=pub,
            printer_id="p1",
            on_finished=finished.append,
        )
        return exec_, job, engine, pub, finished

    def _wait(self, condition_fn, timeout=3.0):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if condition_fn():
                return True
            time.sleep(0.05)
        return False

    def test_successful_execution(self):
        lines = ["G28", "M104 S200", "M109 S200"]
        ex, job, engine, pub, finished = self._make_executor(lines)
        ex.start()
        self.assertTrue(self._wait(lambda: job.status == "COMPLETED"))
        self.assertEqual(engine.send.call_count, len(lines))
        self.assertAlmostEqual(job.progress, 100.0)
        self.assertEqual(len(finished), 1)

    def test_engine_sends_lines_in_order(self):
        lines = ["G28", "M104 S200", "G1 X10"]
        ex, job, engine, _, _ = self._make_executor(lines)
        ex.start()
        self._wait(lambda: job.status == "COMPLETED")
        calls = [c[0][0] for c in engine.send.call_args_list]
        self.assertEqual(calls, lines)

    def test_pause_and_resume(self):
        lines = ["G28"] * 20
        ex, job, engine, _, finished = self._make_executor(lines)
        ex.start()
        time.sleep(0.1)
        ex.pause()
        self.assertTrue(self._wait(lambda: job.status == "PAUSED", timeout=2))
        paused_at = job.current_line_index
        time.sleep(0.2)
        self.assertEqual(job.current_line_index, paused_at)  # not advancing
        ex.resume()
        self.assertTrue(self._wait(lambda: job.status == "COMPLETED", timeout=5))

    def test_cancel_stops_execution(self):
        # Use slow engine to give cancel time to fire
        lines = ["G28"] * 100
        engine = MagicMock()
        def slow_send(cmd):
            time.sleep(0.02)
            return _make_ok_result()
        engine.send.side_effect = slow_send
        store   = JobStore(storage_dir=Path(tempfile.mkdtemp()))
        pub     = MagicMock()
        job     = Job.create("p1", "http://x.com/f.gcode", lines)
        finished = []
        ex = JobExecutor(job=job, command_engine=engine, store=store,
                         publish_state=pub, printer_id="p1",
                         on_finished=finished.append)
        ex.start()
        time.sleep(0.1)
        ex.cancel()
        self.assertTrue(self._wait(lambda: job.status == "CANCELLED", timeout=3))
        self.assertLess(job.current_line_index, len(lines))

    def test_engine_failure_marks_job_failed(self):
        lines = ["G28", "M104 S200"]
        ex, job, engine, _, finished = self._make_executor(lines, engine_result=_make_fail_result())
        ex.start()
        self.assertTrue(self._wait(lambda: job.status == "FAILED", timeout=3))
        self.assertIsNotNone(job.failure_reason)
        self.assertEqual(len(finished), 1)

    def test_publish_called_on_every_line(self):
        lines = ["G28", "M104", "M109"]
        ex, job, engine, pub, _ = self._make_executor(lines)
        ex.start()
        self._wait(lambda: job.status == "COMPLETED")
        # at minimum: PRINTING + 3 line updates + COMPLETED
        self.assertGreaterEqual(pub.call_count, len(lines) + 1)


