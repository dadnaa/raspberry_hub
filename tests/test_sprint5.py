SAMPLE_GCODE = """\
; Generated by Slicer 1.0
%
G28 ; home all axes
M104 S200 ; set nozzle temp
  
M109 S200
G1 X10 Y10 F3000
; just a comment
M84
"""

class TestGcodePipeline(unittest.TestCase):

    def test_filters_comments_and_blanks(self):
        lines = load_from_string(SAMPLE_GCODE)
        for line in lines:
            self.assertFalse(line.startswith(";"))
            self.assertTrue(line.strip())

    def test_filters_percent_marker(self):
        lines = load_from_string(SAMPLE_GCODE)
        self.assertNotIn("%", lines)

    def test_strips_inline_comments(self):
        lines = load_from_string(SAMPLE_GCODE)
        for line in lines:
            self.assertNotIn(";", line)

    def test_correct_line_count(self):
        lines = load_from_string(SAMPLE_GCODE)
        # G28, M104 S200, M109 S200, G1 X10 Y10 F3000, M84 = 5
        self.assertEqual(len(lines), 5)

    def test_order_preserved(self):
        lines = load_from_string(SAMPLE_GCODE)
        self.assertEqual(lines[0], "G28")
        self.assertEqual(lines[1], "M104 S200")

    def test_load_from_file(self):
        with tempfile.NamedTemporaryFile(mode="w", suffix=".gcode", delete=False) as f:
            f.write(SAMPLE_GCODE)
            path = f.name
        try:
            lines = load_from_file(path)
            self.assertEqual(len(lines), 5)
        finally:
            os.unlink(path)

    def test_file_not_found(self):
        from src.jobs.gcode_pipeline import load_from_file
        with self.assertRaises(FileNotFoundError):
            load_from_file("/nonexistent/path/file.gcode")

    def test_is_executable(self):
        self.assertTrue(_is_executable("G28"))
        self.assertTrue(_is_executable("M104 S200"))
        self.assertTrue(_is_executable("T0"))
        self.assertFalse(_is_executable(""))
        self.assertFalse(_is_executable(";comment"))
        self.assertFalse(_is_executable("%"))

    def test_strip_inline_comment(self):
        self.assertEqual(_strip_line("G28 ; home"), "G28")
        self.assertEqual(_strip_line("  M104 S200  "), "M104 S200")
        self.assertEqual(_strip_line("; full comment"), "")


