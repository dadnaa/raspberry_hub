class TestJobManager(unittest.TestCase):

    def _make_manager(self, tmpdir=None):
        engine = MagicMock()
        engine.send.return_value = _make_ok_result()
        pub     = MagicMock()
        store   = JobStore(storage_dir=Path(tmpdir or tempfile.mkdtemp()))
        mgr     = JobManager(
            command_engine=engine,
            publish_state=pub,
            printer_id="p1",
            store=store,
        )
        return mgr, engine, pub, store

    def _start_msg(self, lines_str=None):
        # Uses a local file with real content
        lines = lines_str or "G28\nM104 S200\nM109 S200\n"
        f = tempfile.NamedTemporaryFile(mode="w", suffix=".gcode", delete=False)
        f.write(lines)
        f.close()
        return StartJobMessage(
            printerId="p1",
            jobId=f"job-{id(f)}",
            fileUrl=f.name,
        ), f.name

    def _wait(self, cond, timeout=4.0):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if cond():
                return True
            time.sleep(0.05)
        return False

    def test_submit_and_complete(self):
        mgr, _, _, _ = self._make_manager()
        msg, path = self._start_msg()
        try:
            job = mgr.submit(msg)
            self.assertTrue(self._wait(lambda: job.status == "COMPLETED"))
        finally:
            os.unlink(path)

    def test_only_one_active_job(self):
        mgr, engine, _, _ = self._make_manager()
        # Slow engine so first job stays active
        def slow_send(cmd):
            time.sleep(0.05)
            return _make_ok_result()
        engine.send.side_effect = slow_send

        msg1, p1 = self._start_msg("G28\nM104\nM109\nG1 X10\nG1 X20\n")
        msg2, p2 = self._start_msg("G28\nM105\n")
        try:
            job1 = mgr.submit(msg1)
            time.sleep(0.05)
            job2 = mgr.submit(msg2)
            # job2 must be QUEUED while job1 is running
            self.assertIn(job2.status, ("QUEUED",))
            self._wait(lambda: job1.status == "COMPLETED", timeout=5)
            self._wait(lambda: job2.status == "COMPLETED", timeout=5)
        finally:
            os.unlink(p1); os.unlink(p2)

    def test_cancel_queued_job(self):
        mgr, engine, _, _ = self._make_manager()
        def slow_send(cmd):
            time.sleep(0.1)
            return _make_ok_result()
        engine.send.side_effect = slow_send

        msg1, p1 = self._start_msg("G28\nM104\nM109\nG1 X10\nG1 X20\n")
        msg2, p2 = self._start_msg("G28\n")
        try:
            mgr.submit(msg1)
            time.sleep(0.05)
            job2 = mgr.submit(msg2)
            ok = mgr.cancel(msg2.jobId)
            self.assertTrue(ok)
            self.assertEqual(job2.status, "CANCELLED")
        finally:
            os.unlink(p1); os.unlink(p2)

    def test_recover_requeues_interrupted_jobs(self):
        tmpdir = tempfile.mkdtemp()
        mgr, engine, _, store = self._make_manager(tmpdir=tmpdir)

        # Manually persist a mid-execution job
        job = Job.create("p1", "/dev/null", ["G28", "M104", "M109"])
        job.status             = "PRINTING"
        job.current_line_index = 1
        job.started_at         = "2026-01-01T00:00:00+00:00"
        store.save(job)

        # New manager on same store simulates restart
        mgr2, _, _, _ = self._make_manager(tmpdir=tmpdir)
        # Patch load so it uses in-memory lines (no real file)
        with patch("src.jobs.job_manager.load", return_value=["G28", "M104", "M109"]):
            recovered = mgr2.recover()
        self.assertGreaterEqual(recovered, 1)


