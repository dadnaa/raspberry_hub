class TestJobStore(unittest.TestCase):

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.store  = JobStore(storage_dir=Path(self.tmpdir))

    def _make_job(self):
        return Job.create("p1", "http://x.com/f.gcode", ["G28", "M105"])

    def test_save_and_load(self):
        job = self._make_job()
        self.store.save(job)
        loaded = self.store.load(job.job_id)
        self.assertIsNotNone(loaded)
        self.assertEqual(loaded.job_id, job.job_id)

    def test_load_nonexistent(self):
        self.assertIsNone(self.store.load("does-not-exist"))

    def test_delete(self):
        job = self._make_job()
        self.store.save(job)
        self.store.delete(job.job_id)
        self.assertIsNone(self.store.load(job.job_id))

    def test_load_all(self):
        jobs = [self._make_job() for _ in range(3)]
        for j in jobs:
            self.store.save(j)
        loaded = self.store.load_all()
        self.assertEqual(len(loaded), 3)

    def test_exists(self):
        job = self._make_job()
        self.assertFalse(self.store.exists(job.job_id))
        self.store.save(job)
        self.assertTrue(self.store.exists(job.job_id))

    def test_path_traversal_safe(self):
        """Ensure malicious job IDs cannot write outside storage dir."""
        job = self._make_job()
        job.job_id = "../../etc/passwd"
        # save should succeed but write to safe path inside tmpdir
        self.store.save(job)
        files = list(Path(self.tmpdir).glob("**/*.json"))
        for f in files:
            self.assertTrue(str(f).startswith(self.tmpdir))

    def test_concurrent_writes_safe(self):
        errors = []
        jobs = [self._make_job() for _ in range(10)]

        def writer(j):
            try:
                for _ in range(5):
                    self.store.save(j)
            except Exception as e:
                errors.append(e)

        threads = [threading.Thread(target=writer, args=(j,)) for j in jobs]
        for t in threads: t.start()
        for t in threads: t.join()
        self.assertEqual(errors, [])


