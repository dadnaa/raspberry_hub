class TestJobModel(unittest.TestCase):

    def _make_job(self, lines=None):
        return Job.create(
            printer_id="p1",
            file_url="http://example.com/test.gcode",
            gcode_lines=lines or ["G28", "M104 S200", "M109 S200"],
        )

    def test_create_sets_defaults(self):
        job = self._make_job()
        self.assertEqual(job.status, "QUEUED")
        self.assertEqual(job.current_line_index, 0)
        self.assertEqual(job.progress, 0.0)
        self.assertEqual(job.total_lines, 3)
        self.assertIsNotNone(job.created_at)

    def test_state_transitions(self):
        job = self._make_job()
        job.mark_loading()
        self.assertEqual(job.status, "LOADING")
        job.mark_printing()
        self.assertEqual(job.status, "PRINTING")
        self.assertIsNotNone(job.started_at)
        job.mark_paused()
        self.assertEqual(job.status, "PAUSED")
        job.mark_printing()    # resume
        self.assertIsNone(job.paused_at)
        job.mark_completed()
        self.assertEqual(job.status, "COMPLETED")
        self.assertAlmostEqual(job.progress, 100.0)

    def test_mark_failed(self):
        job = self._make_job()
        job.mark_failed("serial timeout")
        self.assertEqual(job.status, "FAILED")
        self.assertEqual(job.failure_reason, "serial timeout")
        self.assertIsNotNone(job.finished_at)

    def test_mark_cancelled(self):
        job = self._make_job()
        job.mark_cancelled()
        self.assertEqual(job.status, "CANCELLED")

    def test_progress_calculation(self):
        job = self._make_job(["G28"] * 10)
        job.current_line_index = 5
        job.update_progress()
        self.assertAlmostEqual(job.progress, 50.0)

    def test_next_line(self):
        job = self._make_job(["G28", "M104"])
        self.assertEqual(job.next_line, "G28")
        job.current_line_index = 1
        self.assertEqual(job.next_line, "M104")
        job.current_line_index = 2
        self.assertIsNone(job.next_line)

    def test_json_roundtrip(self):
        job = self._make_job()
        job.mark_printing()
        restored = Job.from_json(job.to_json())
        self.assertEqual(restored.job_id,     job.job_id)
        self.assertEqual(restored.status,     job.status)
        self.assertEqual(restored.gcode_lines, job.gcode_lines)
        self.assertEqual(restored.started_at, job.started_at)

    def test_is_active(self):
        job = self._make_job()
        job.mark_printing()
        self.assertTrue(job.is_active)
        job.mark_completed()
        self.assertFalse(job.is_active)
        self.assertTrue(job.is_terminal)


